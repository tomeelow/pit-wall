// Generates TypeScript types from the contract's JSON Schema.
// Usage: node scripts/gen-contract.mjs [schemaDir] [outDir]
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { compile } from "json-schema-to-typescript";

const [schemaDir = "../contract", outDir = "src/contract"] = process.argv.slice(2);
const banner = "// Generated by `make contract` from contract/*.schema.json. Do not edit.";

await mkdir(outDir, { recursive: true });
for (const file of (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = JSON.parse(await readFile(join(schemaDir, file), "utf8"));
  const ts = await compile(schema, schema.title, { bannerComment: banner, additionalProperties: false });
  await writeFile(join(outDir, `${basename(file, ".schema.json")}.ts`), ts);
}
